import assert from "node:assert/strict";
import fs from "node:fs";
import {execFileSync} from "node:child_process";
import test from "node:test";

const read = p => fs.readFileSync("site/" + p, "utf8");
const hubs = ["ages/activities-for-3-year-olds-at-home.html", "collections/no-prep-activities-for-preschoolers.html", "collections/independent-activities-for-preschoolers.html"];
const flatChecks = ["EVERY reachable child", "TWO intact LARGE", "ONE square and ONE triangle", "SMALL GAP", "NO opening door", "not family-tested by Kid Activity Lab", "accounts for BOTH"];

test("House card explicitly withdraws standing recipe and checks owned flat shapes before action", () => {
  const h = read("cards/magnetic-tile-house.html"), steps = h.indexOf('class="flat-house-steps"');
  assert.ok(steps > 0);
  for (const s of flatChecks) assert.ok(h.includes(s), s);
  for (const s of ["Flat picture only", "standing-house version is withdrawn", "Fit or decline:", "Adult and space:", "Stop:", "Adult model:"]) assert.ok(h.indexOf(s) > 0 && h.indexOf(s) < steps, s);
  assert.match(h, /broad edge facing the square and opposite corner pointing away/);
  assert.match(h, /no magnetic join, snap, force, upright wall or supported roof/);
  assert.match(h, /point, watch or decline/);
  assert.match(h, /Unknown identity, labels, condition or uncontrolled younger reach means decline/);
  assert.doesNotMatch(h, /<iframe|3 min|low mess|quiet time|Make walls\.|Add a roof\.|Put a toy inside\.|Open the door\.|name="robots"/);
  assert.match(h, /canonical" href="https:\/\/kidactivitylab.com\/cards\/magnetic-tile-house.html"/);
  assert.ok(h.indexOf("Sources and testing status") > steps);
});

test("Actual CSV house dispatch and canonical ordinary hubs reproduce generated bytes", () => {
  const code = `import sys,json,csv
sys.path.insert(0,'scripts')
import generate_card_pages as c,generate_seo_pages as s
from contributor_pages import with_contributor_credit
row=next(r for r in csv.DictReader(open('data/video_activity_sources.csv')) if r['source_id']=='yt-magna-tiles-three-builds')
assert row['kid_step_1']=='Make walls.'
assert 'magnetic-tile-house' not in c.QUICK_CARD_SLUGS and 'magnetic-tile-house' not in c.QUICK_CARD_OVERRIDES
out={'cards/magnetic-tile-house.html':c.page(row,'magnetic-tile-house'),'cards.html':c.cards_index()}
for p in s.PAGES:
 if 'magnetic-tile-house' in p.get('activities',[]):out[p['path']]=s.page_html(p)
assert 'magnetic-tile-house' not in next(p for p in s.PAGES if p['path']=='collections/indoor-activities-for-preschoolers.html')['activities']
print(json.dumps({p:with_contributor_credit(h,p) for p,h in out.items()}))`;
  const out = JSON.parse(execFileSync("python3", ["-B", "-c", code], {encoding: "utf8", maxBuffer: 16 * 1024 * 1024}));
  assert.equal(Object.keys(out).length, 6);
  for (const [p, h] of Object.entries(out)) assert.equal(h, read(p), p);
  for (const p of hubs) {
    const h = [...read(p).matchAll(/<article\b[\s\S]*?<\/article>/g)].map(m => m[0]).find(h => h.includes("<h2>Magnetic Tile House</h2>"));
    assert.ok(h, p);
    for (const s of flatChecks) assert.ok(h.includes(s), p + ": " + s);
    assert.ok(h.indexOf("Stop:") < h.indexOf('<ol class="card-steps">'));
    assert.match(h, /Adult stays beside setup/);
    assert.doesNotMatch(h, /3 min|low help|quiet time|Make walls\.|Open the door\./);
  }
});

test("Earlier Building callout, readiness, chooser and Toy Home route to a DIFFERENT checked job", () => {
  const h = read("collections/building-activities-for-4-year-olds.html");
  const callout = h.match(/<div class="callout">[\s\S]*?<\/div>/)[0];
  assert.match(callout, /old block-or-tile Toy Home instructions are withdrawn/);
  assert.match(callout, /DIFFERENT materials: an already-open box and a suitable owned car/);
  assert.match(callout, /Read its checks before handling materials or decline/);
  assert.match(callout, /href="\.\.\/cards\/box-garage.html"/);
  assert.ok(h.indexOf(callout) < h.indexOf('class="building-readiness"'));
  assert.match(h, /larger-block\/watch suggestion does NOT override either activity&#x27;s checks/);
  assert.doesNotMatch(h, /six to ten large blocks|six to ten intact|Make two side walls\.|Use three walls and leave the roof off\./);
  const module = h.match(/<article[^>]*id="magnetic-tile-house"[\s\S]*?<\/article>/)[0];
  assert.match(module, /<h2>Toy Home<\/h2>/);
  assert.match(module, /DIFFERENT materials/);
  assert.match(module, /flat tile picture is NOT a room/);
  assert.doesNotMatch(module, /<ol|href="\.\.\/cards\/magnetic-tile-house.html"/);
  assert.ok(module.indexOf('href="../cards/box-garage.html"') < module.indexOf("After the linked checks"));
  assert.match(h, /href="#magnetic-tile-house">Toy Home<\/a>/);
  assert.match(h, /href="#block-tower">Wide-Base Tower<\/a>/);
  assert.equal((h.match(/class="seo-activity building-build"/g) || []).length, 9);
});

test("Flat-house discovery distinguishes its new task without adding owners or phantom Indoor routes", () => {
  const h = [...read("cards.html").matchAll(/<a class="mini-card"[\s\S]*?<\/a>/g)].map(m => m[0]).find(h => h.includes("cards/magnetic-tile-house.html"));
  assert.match(h, /Flat PICTURE, not a toy room; adult stays beside/);
  assert.doesNotMatch(h, /3 min|small toy/);
  assert.doesNotMatch(read("cards/magnetic-tile-house.html"), /href="\.\.\/collections\/indoor-activities-for-preschoolers.html"/);
  assert.doesNotMatch(read("collections/indoor-activities-for-preschoolers.html"), /id="magnetic-tile-house"|<h2>Magnetic Tile House<\/h2>/);
  assert.equal((read("cards.html").match(/class="mini-card"/g) || []).length, 36);
  assert.equal((read("sitemap.xml").match(/<loc>/g) || []).length, 65);
  assert.ok(read("sitemap.xml").includes("https://kidactivitylab.com/cards/magnetic-tile-house.html"));
});
